using System.Text.RegularExpressions;

namespace Bdtheque.Infrastructure.Tests;

/// <summary>
/// The rules of form of the technical documentation (docs/tech/documentation/consulter-et-maintenir.md, Forme), checked on
/// the docs/tech folder of a repository: the one of this repository, or a fixture of the tests.
/// </summary>
internal sealed partial class TechnicalDocumentationChecker(string repository)
{
    private readonly string _documentation = Path.Combine(repository, "docs", "tech");

    public IReadOnlyList<string> Check()
    {
        var violations = new List<string>();
        foreach (var folder in Folders())
            CheckMap(folder, violations);
        var files = RepositoryFilePaths().ToList();
        foreach (var page in Directory.EnumerateFiles(_documentation, "*.md", SearchOption.AllDirectories).Where(IsPage))
            CheckPage(page, files, violations);
        foreach (var markdown in Directory.EnumerateFiles(_documentation, "*.md", SearchOption.AllDirectories))
        {
            CheckLinks(markdown, violations);
            CheckDiagrams(markdown, violations);
        }

        return violations;
    }

    private void CheckMap(string folder, List<string> violations)
    {
        var index = Path.Combine(folder, "index.md");
        if (!File.Exists(index))
        {
            violations.Add($"{Relative(folder)}: no index.md");
            return;
        }

        if (File.ReadLines(index).FirstOrDefault() == "---")
            violations.Add($"{Relative(index)}: a map has no front matter");

        var entries = MapEntryPattern().Matches(File.ReadAllText(index))
            .ToDictionary(entry => entry.Groups["path"].Value, entry => entry.Groups["description"].Value);
        foreach (var page in Directory.GetFiles(folder, "*.md").Where(IsPage))
        {
            var name = Path.GetFileName(page);
            if (!entries.TryGetValue(name, out var description))
                violations.Add($"{Relative(index)}: {name} is not listed");
            else if (description != FrontMatter.Read(page)?.Value("description"))
                violations.Add($"{Relative(index)}: the entry of {name} does not give its description");
        }

        violations.AddRange(Directory.GetDirectories(folder).Where(ContainsMarkdown)
            .Select(sub => $"{Path.GetFileName(sub)}/index.md")
            .Where(sub => !entries.ContainsKey(sub))
            .Select(sub => $"{Relative(index)}: {sub} is not listed"));
        violations.AddRange(entries.Keys.Where(path => !File.Exists(Path.Combine(folder, path)))
            .Select(path => $"{Relative(index)}: lists {path}, which does not exist"));
    }

    private void CheckPage(string page, List<string> files, List<string> violations)
    {
        var header = FrontMatter.Read(page);
        if (header is null)
        {
            violations.Add($"{Relative(page)}: no front matter");
            return;
        }

        var title = header.Value("title");
        if (string.IsNullOrWhiteSpace(title))
            violations.Add($"{Relative(page)}: no title");
        if (string.IsNullOrWhiteSpace(header.Value("description")))
            violations.Add($"{Relative(page)}: no description");
        if (HeadingPattern().Match(File.ReadAllText(page)) is not { Success: true } heading || heading.Groups["title"].Value != title)
            violations.Add($"{Relative(page)}: its heading is not its title '{title}'");

        violations.AddRange(header.Items("code")
            .Where(pattern => !files.Any(Glob(pattern).IsMatch))
            .Select(pattern => $"{Relative(page)}: code '{pattern}' designates no file"));
        if (header.Value("generated") is { } generator && !File.Exists(Path.Combine(repository, generator)))
            violations.Add($"{Relative(page)}: generated by {generator}, which does not exist");
    }

    private void CheckLinks(string markdown, List<string> violations)
    {
        // A link written as code is an example, not a link: code spans are blanked, those that name a link kept apart.
        var text = DoubleBacktickCodePattern().Replace(FencePattern().Replace(File.ReadAllText(markdown), ""), "");
        foreach (Match link in LinkPattern().Matches(text))
        {
            var href = link.Groups["href"].Value;
            if (InsideCodeSpan(text, link.Index) || href.StartsWith("http:", StringComparison.Ordinal)
                || href.StartsWith("https:", StringComparison.Ordinal))
                continue;
            if (href.StartsWith('/'))
            {
                violations.Add($"{Relative(markdown)}: {href} starts from the root, which its reader resolves elsewhere");
                continue;
            }

            var parts = href.Split('#', 2);
            var target = parts[0].Length == 0 ? markdown : Path.GetFullPath(Path.Combine(Path.GetDirectoryName(markdown)!, parts[0]));
            if (!File.Exists(target) && !Directory.Exists(target))
                violations.Add($"{Relative(markdown)}: {href} designates nothing");
            else if (parts.Length == 2 && File.Exists(target) && !Anchors(target).Contains(Uri.UnescapeDataString(parts[1])))
                violations.Add($"{Relative(markdown)}: {href} designates no section");
            else if (File.Exists(target) && Path.GetExtension(target) != ".md"
                     && SymbolPattern().Match(link.Groups["text"].Value) is { Success: true } symbol
                     && !NamesTheFile(symbol.Groups["symbol"].Value, target)
                     && !Declares(target, symbol.Groups["symbol"].Value))
                violations.Add($"{Relative(markdown)}: {symbol.Groups["symbol"].Value} is not in {href}");
        }
    }

    // A diagram answers one question, which the paragraph introducing it asks in a sentence.
    private void CheckDiagrams(string markdown, List<string> violations)
    {
        var lines = File.ReadAllLines(markdown);
        for (var i = 0; i < lines.Length; i++)
        {
            if (!lines[i].TrimStart().StartsWith("```mermaid", StringComparison.Ordinal))
                continue;
            var before = lines.Take(i).Reverse().SkipWhile(string.IsNullOrWhiteSpace).TakeWhile(line => !string.IsNullOrWhiteSpace(line));
            if (!before.Any(line => line.Contains('?', StringComparison.Ordinal)))
                violations.Add($"{Relative(markdown)}: a diagram is not introduced by a paragraph that asks its question");
        }
    }

    private static bool InsideCodeSpan(string text, int index) =>
        InlineCodePattern().Matches(text).Any(code => code.Index < index && index < code.Index + code.Length);

    // A Razor component is named by its file, which declares no class.
    private static bool NamesTheFile(string symbol, string file) =>
        symbol.Contains('/', StringComparison.Ordinal) || symbol == Path.GetFileName(file)
        || (Path.GetExtension(file) == ".razor" && symbol == Path.GetFileNameWithoutExtension(file));

    // Each part of a dotted symbol (Type.Member) is a word of the file.
    private static bool Declares(string file, string symbol)
    {
        var content = File.ReadAllText(file);
        return symbol.Split('.').All(part => Regex.IsMatch(content, $@"\b{Regex.Escape(part)}\b"));
    }

    private static bool IsPage(string path) => Path.GetFileName(path) != "index.md";

    private static bool ContainsMarkdown(string folder) =>
        Directory.EnumerateFiles(folder, "*.md", SearchOption.AllDirectories).Any();

    private IEnumerable<string> Folders() =>
        new[] { _documentation }.Concat(Directory.GetDirectories(_documentation, "*", SearchOption.AllDirectories)).Where(ContainsMarkdown);

    private string Relative(string path) => Path.GetRelativePath(repository, path).Replace('\\', '/');

    // Anchors as GitHub renders them, which the links follow.
    private static HashSet<string> Anchors(string markdown) =>
        AnyHeadingPattern().Matches(File.ReadAllText(markdown))
            .Select(heading => AnchorSpacePattern().Replace(AnchorDropPattern().Replace(heading.Groups["title"].Value.Trim().ToLowerInvariant(), ""), "-"))
            .ToHashSet();

    private IEnumerable<string> RepositoryFilePaths()
    {
        string[] ignored = ["bin", "obj", ".git", "TestResults", "node_modules"];
        var pending = new Stack<string>([repository]);
        while (pending.TryPop(out var directory))
        {
            foreach (var file in Directory.GetFiles(directory))
                yield return Path.GetRelativePath(repository, file).Replace('\\', '/');
            foreach (var sub in Directory.GetDirectories(directory).Where(sub => !ignored.Contains(Path.GetFileName(sub))))
                pending.Push(sub);
        }
    }

    private static Regex Glob(string pattern) =>
        new("^" + Regex.Escape(pattern).Replace(@"\*\*", "\u0001").Replace(@"\*", "[^/]*").Replace("\u0001", ".*") + "$");

    /// <summary>The front matter of a page: a key and its value, or a key and the items of its list.</summary>
    private sealed partial class FrontMatter
    {
        private readonly Dictionary<string, List<string>> _keys = [];

        public static FrontMatter? Read(string path)
        {
            var lines = File.ReadAllLines(path);
            if (lines.Length == 0 || lines[0] != "---")
                return null;

            var header = new FrontMatter();
            List<string>? current = null;
            foreach (var line in lines.Skip(1).TakeWhile(line => line != "---"))
            {
                if (KeyPattern().Match(line) is { Success: true } key)
                    header._keys[key.Groups["key"].Value] = current = [key.Groups["value"].Value];
                else if (current is not null && ItemPattern().Match(line) is { Success: true } item)
                    current.Add(item.Groups["value"].Value);
            }

            return header;
        }

        public string? Value(string key) =>
            _keys.TryGetValue(key, out var lines) && lines[0].Length > 0 ? Unquote(lines[0]) : null;

        public IEnumerable<string> Items(string key) =>
            _keys.TryGetValue(key, out var lines) ? lines.Skip(1).Select(Unquote) : [];

        private static string Unquote(string value) =>
            value.Length >= 2 && value[0] == '\'' && value[^1] == '\'' ? value[1..^1].Replace("''", "'") : value;

        [GeneratedRegex(@"^(?<key>[a-z_]+):\s*(?<value>.*?)\s*$")]
        private static partial Regex KeyPattern();

        [GeneratedRegex(@"^\s+-\s+(?<value>.*?)\s*$")]
        private static partial Regex ItemPattern();
    }

    [GeneratedRegex(@"^\* \[(?<title>[^\]]+)\]\((?<path>[^)]+)\)(?: - (?<description>.*?))?\r?$", RegexOptions.Multiline)]
    private static partial Regex MapEntryPattern();

    [GeneratedRegex(@"\[(?<text>[^\]]*)\]\((?<href>[^)\s]+)\)")]
    private static partial Regex LinkPattern();

    [GeneratedRegex(@"^\s*```.*?^\s*```", RegexOptions.Multiline | RegexOptions.Singleline)]
    private static partial Regex FencePattern();

    [GeneratedRegex(@"``.+?``")]
    private static partial Regex DoubleBacktickCodePattern();

    [GeneratedRegex(@"`[^`\n]*`")]
    private static partial Regex InlineCodePattern();

    // A link whose whole text is a code span: a symbol, or a file.
    [GeneratedRegex(@"^`(?<symbol>[^`]+)`$")]
    private static partial Regex SymbolPattern();

    [GeneratedRegex(@"^# (?<title>.+?)\r?$", RegexOptions.Multiline)]
    private static partial Regex HeadingPattern();

    [GeneratedRegex(@"^#{1,6} (?<title>.+?)\r?$", RegexOptions.Multiline)]
    private static partial Regex AnyHeadingPattern();

    [GeneratedRegex(@"[^\p{L}\p{N}\s_-]")]
    private static partial Regex AnchorDropPattern();

    [GeneratedRegex(@"\s")]
    private static partial Regex AnchorSpacePattern();
}
